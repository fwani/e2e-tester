"""엑셀 통로의 상한 (기능 014 · FR-036·FR-036c).

**여기에는 이 기능이 새로 도입하는 상한만 둔다.** 제품 공통 상한 — 프로젝트당 테스트 번호,
그룹 접두어 형식, 이름 길이 — 은 이미 :mod:`itb.domain.test_case` 에 있고, 가져오기는 그것을
**참조한다**. 값을 여기 베껴 두면 누군가 저쪽을 바꿀 때 두 곳 중 하나만 바뀐다.
FR-036c 가 요구하는 것은 "값이 같다"가 아니라 "출처가 하나다"이다.

상한이 두 종류인 이유 (FR-036a):

- **파일을 읽는 상한** (이 파일) — 이 정도 크기까지는 해석해 보겠다는 뜻
- **프로젝트가 수용하는 양** (:data:`itb.domain.test_case.MAX_TEST_NUMBER`) — 실제로 만들 수
  있는 양

행 5,000 과 테스트 999 가 어긋나 보이는 것은 의도한 것이다. 둘을 같은 값으로 맞추면 "읽을 수는
있지만 이 프로젝트에는 못 넣는다"는 상태를 표현할 수 없게 된다.
"""

MAX_UPLOAD_BYTES = 100 * 1024 * 1024
"""업로드 파일 크기 상한 (100MB).

상한 + 1 바이트만 읽어 초과를 판정한다 — 전체를 메모리에 올린 뒤 재는 것은 상한이 없는 것과
같다. :mod:`itb.storage.session_files` 가 쓰는 수법과 같다.
"""

MAX_UNCOMPRESSED_BYTES = 500 * 1024 * 1024
"""압축을 푼 뒤의 총 바이트 상한 (500MB).

``.xlsx`` 는 zip 이다. 100MB 짜리 파일이 압축을 풀면 수십 GB 가 될 수 있으므로
:data:`MAX_UPLOAD_BYTES` 만으로는 zip 폭탄을 막지 못한다. 열기 **전에**
``ZipFile.infolist()`` 의 ``file_size`` 합으로 판정한다 — 막는 시점이 늦으면 막지 않은 것과 같다.
"""

MAX_COMPRESSION_RATIO = 100
"""압축비 상한.

총량이 :data:`MAX_UNCOMPRESSED_BYTES` 안에 들어도, 압축비가 비정상적으로 높으면 정상적인
스프레드시트가 아니다. 총량 검사만으로는 작은 폭탄을 놓친다.
"""

MAX_SHEETS = 200
"""시트 수 상한."""

MAX_DATA_ROWS = 5000
"""파일 전체의 데이터 행 수 상한 (머리글 행 제외).

시트별이 아니라 **전체** 합이다. 시트 200개 × 행 5,000 을 허용하면 상한이 없는 것과 같다.
"""

MAX_CELL_CHARS = 32767
"""셀 한 칸의 글자 수 상한.

우리가 정한 것이 아니라 엑셀 형식 자체의 상한이다. 넘으면 자르고 잘렸음을 칸 안에 표시한다
(FR-010) — 파일 생성을 실패시키지 않는다.
"""

MAX_SHEET_NAME_CHARS = 31
"""시트 이름 글자 수 상한. 이것도 엑셀 형식의 상한이다."""

XLSX_MEDIA_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
"""``.xlsx`` 의 MIME 타입."""

MAX_IMPORT_PLANS = 8
"""서버가 동시에 들고 있는 가져오기 계획 수 상한. 넘으면 오래된 것부터 버린다."""

IMPORT_PLAN_TTL_SECONDS = 30 * 60
"""가져오기 계획의 수명 (30분).

계획은 메모리에만 있고 디스크에 쓰지 않는다 — 확정 전에는 아무것도 만들지 않아야 하는데
(FR-016), 디스크에 쓰면 그 자체가 "만든 것"이 된다.
"""
