"""공유 묶음 — 프로젝트·테스트를 파일 하나로 내보내고 되받는다 (기능 019).

이 도구는 단독 로컬 도구라 각자의 테스트가 각자의 장비에만 있다. 프로젝트 디렉터리를
그대로 건네도 쓸 수 없는 이유가 셋이다 — ① 민감 값이 설치별 키로 봉인돼 열리지 않고
② 받는 쪽 목록에 나타나지 않으며 ③ 테스트 식별자가 겹친다. 이 패키지가 그 셋을 해결한
**전달 가능한 파일 하나**를 만들고 되읽는다.

모듈:

- :mod:`~itb.sharing.limits` — 이 기능 고유 상한
- :mod:`~itb.sharing.bundle` — 묶음 모델과 필요 값 산출
- :mod:`~itb.sharing.builder` — 프로젝트·테스트 → 묶음, 내보내기 검토 요약
- :mod:`~itb.sharing.reader` — 바이트 → 묶음 (상한·별칭 금지·선언 보충·도메인 검증)
- :mod:`~itb.sharing.planner` — 묶음 + 대상 프로젝트 → 가져오기 계획
- :mod:`~itb.sharing.applier` — 계획 확정 → 결과 (원자적)
- :mod:`~itb.sharing.plan_store` — 메모리 계획 보관소 (TTL 30분)

**이 패키지는 `itb.secrets` 를 임포트하지 않는다.** `.importlinter` 의
`sharing-cannot-reach-secrets` 계약이 강제한다. 민감 값이 묶음에 들어갈 **경로 자체가
없어야** "담지 않는다"가 약속이 아니라 구조가 된다 (019 research R3). 「이 변수에 이미
값이 있는가」 같은 교차 조회는 라우터(`itb.api.routes.sharing`)가 맡는다 — 라우터는 양쪽을
다 임포트할 수 있다.

**`itb.portability`(엑셀, 014)와 합치지 않는다.** 그쪽의 경계는 "엑셀은 테스트의 두 번째
표현이 아니다"이고 그래서 초안(`Draft`)만 만든다. 이쪽은 **스텝을 그대로 옮기는 것이 존재
이유**다. 한 패키지에 두면 두 정책이 부딪히고, 엑셀 경로가 스텝을 다루게 되는 길이 열린다
(019 research R8).
"""
